#define _GNU_SOURCE
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <sched.h>
#include <sys/utsname.h>

int main(int argc, char **argv) {
    struct utsname uts;
    if (uname(&uts) == 0) {
        printf("[C-APP] Running on %s %s (%s) - PID=%d\n",
               uts.sysname, uts.release, uts.machine, getpid());
    }

    cpu_set_t set;
    CPU_ZERO(&set);
    if (sched_getaffinity(0, sizeof(set), &set) == 0) {
        printf("[C-APP] Online SMP CPUs detected via sched_getaffinity: %d\n", CPU_COUNT(&set));
    }

    const char *out_path = (argc > 1) ? argv[1] : "/tmp/c_report.txt";
    FILE *fp = fopen(out_path, "w");
    if (!fp) {
        perror("fopen");
        return 1;
    }
    fprintf(fp, "Generated by C (musl static) on Tinux kernel!\n");
    fclose(fp);
    printf("[C-APP] Successfully wrote report to %s\n", out_path);
    return 0;
}
